"""Write src/canvas/bamTypes.ts: the BAM Data Store object and dataset types.

They come from bam-masterdata (https://github.com/BAMresearch/bam-masterdata), datamodel v0,
which is what the Data Store uses. Run it again when bam-masterdata changes:

    git clone --depth 1 https://github.com/BAMresearch/bam-masterdata /tmp/bam-masterdata
    python3 scripts/bam-types.py /tmp/bam-masterdata

The files are only read (parsed), never imported or run.
"""

import ast
import json
import subprocess
import sys
from pathlib import Path

# Settings of the ELN itself, not something to model data with.
SKIP = {"SEARCH_QUERY", "GENERAL_ELN_SETTINGS"}


def first_line(text: str) -> str:
    # Descriptions are "English//German"; keep the English part.
    return " ".join(text.split("//")[0].split())


def read(path: Path):
    out = []
    for node in ast.walk(ast.parse(path.read_text(encoding="utf8"))):
        if not isinstance(node, ast.ClassDef):
            continue
        for stmt in node.body:
            if not (isinstance(stmt, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "defs" for t in stmt.targets)):
                continue
            call = stmt.value
            if not (isinstance(call, ast.Call) and isinstance(call.func, ast.Name)):
                continue
            kind = {"ObjectTypeDef": "object", "DatasetTypeDef": "dataset"}.get(call.func.id)
            if not kind:
                continue
            args = {k.arg: k.value.value for k in call.keywords
                    if isinstance(k.value, ast.Constant) and isinstance(k.value.value, str)}
            code = args.get("code", "")
            if code and code not in SKIP:
                out.append((kind, code, first_line(args.get("description", ""))))
    return out


def main(repo: str) -> None:
    root = Path(repo)
    model = root / "bam_masterdata" / "datamodel" / "v0"
    found = {}
    for path in sorted(model.rglob("*.py")):
        for kind, code, description in read(path):
            found.setdefault((kind, code), description)
    commit = subprocess.run(["git", "-C", repo, "log", "-1", "--format=%h %cs"], capture_output=True, text=True).stdout.strip()

    def items(kind):
        rows = sorted((c, d) for (k, c), d in found.items() if k == kind)
        return ",\n".join(f"  {{ code: {json.dumps(c)}, description: {json.dumps(d, ensure_ascii=False)} }}" for c, d in rows)

    out = Path(__file__).resolve().parent.parent / "src" / "canvas" / "bamTypes.ts"
    out.write_text(f"""/**
 * The object and dataset types of the BAM Data Store, from bam-masterdata (datamodel v0,
 * commit {commit}). Generated by scripts/bam-types.py; do not edit by hand.
 */

export interface BamType {{
  code: string; // e.g. EXPERIMENTAL_STEP.SEM: a more specific kind of EXPERIMENTAL_STEP
  description: string;
}}

export const BAM_TYPES_SOURCE = "bam-masterdata v0 ({commit})";

export const BAM_OBJECT_TYPES: BamType[] = [
{items("object")},
];

export const BAM_DATASET_TYPES: BamType[] = [
{items("dataset")},
];
""", encoding="utf8")
    n_obj = sum(1 for k, _ in found if k == "object")
    n_ds = sum(1 for k, _ in found if k == "dataset")
    print(f"wrote {out}: {n_obj} object types, {n_ds} dataset types ({commit})")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/bam-masterdata")
